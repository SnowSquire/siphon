#!/usr/bin/env bash
# Cross-builds shaderc for x86_64-pc-windows-msvc on Linux.
#
# libplacebo needs a GLSL compiler at run time: without one it links but cannot
# compile its shaders. This produces the static `shaderc_combined` archive that
# gets linked into `libplacebo-<api>.dll`, so the payload gains no second DLL.
#
# Usage: scripts/build-shaderc-win.sh [--clean]
#
# Knobs (defaults match the dev box):
#   SHADERC_SRC     source checkout     $LIBS_ROOT/shaderc
#   SHADERC_BUILD   build directory     $SHADERC_SRC/build-win
#   SHADERC_PREFIX  install prefix      $SHADERC_SRC/win-prefix
#   SHADERC_SPLAT   xwin CRT/SDK splat  ~/.cache/xwin
#   SHADERC_VERSION pinned tag          v2026.4
#   LIBS_ROOT       parent for the above ~/Projects/Code/Libs
#
# Output: $SHADERC_PREFIX/lib/shaderc_combined.lib, include/shaderc/*, and a
# lib/pkgconfig/shaderc.pc. shaderc's own shaderc.pc names the shared target,
# which would put a second DLL in the payload; the one written here names the
# combined static archive instead. It is built against the dynamic CRT (/MD),
# like libplacebo and the exes, so the payload uses the system VC++ runtime.
#
# Feed the prefix to libplacebo:
#   SHADERC_PREFIX=$SHADERC_PREFIX scripts/build-libplacebo-win.sh

set -euo pipefail

root="${LIBS_ROOT:-$HOME/Projects/Code/Libs}"
src="${SHADERC_SRC:-$root/shaderc}"
prefix="${SHADERC_PREFIX:-$src/win-prefix}"
splat="${SHADERC_SPLAT:-$HOME/.cache/xwin}"
version="${SHADERC_VERSION:-v2026.4}"
build="${SHADERC_BUILD:-$src/build-win}"
toolchain="$root/shaderc-msvc-cross.cmake"

clean=0
if [[ "${1:-}" == "--clean" ]]; then
    clean=1
fi

for tool in clang-cl llvm-lib llvm-rc lld-link cmake ninja git python3; do
    command -v "$tool" >/dev/null || {
        echo "missing $tool; the Windows cross-build needs LLVM, CMake and Ninja" >&2
        exit 1
    }
done

if [[ ! -d "$splat/crt/include" ]]; then
    echo "no xwin splat at $splat: xwin --accept-license --cache-dir ~/.cache/xwin-cache splat --output ~/.cache/xwin" >&2
    exit 1
fi

if [[ ! -d "$src/.git" ]]; then
    echo "cloning shaderc $version into $src"
    mkdir -p "$(dirname "$src")"
    git clone --quiet --depth 1 --branch "$version" https://github.com/google/shaderc "$src"
fi
if [[ ! -d "$src/third_party/glslang" ]]; then
    echo "syncing shaderc's third_party checkouts"
    python3 "$src/utils/git-sync-deps"
fi

cat >"$toolchain" <<'EOF'
# Generated by siphon's scripts/build-shaderc-win.sh: CMake cross file that
# builds Windows x86_64/MSVC code with clang-cl and the xwin CRT/SDK. INCLUDE
# and LIB carry the SDK paths, which clang-cl and lld-link read themselves.
set(CMAKE_SYSTEM_NAME Windows)
set(CMAKE_SYSTEM_PROCESSOR x86_64)
set(CMAKE_C_COMPILER clang-cl)
set(CMAKE_CXX_COMPILER clang-cl)
set(CMAKE_LINKER lld-link)
set(CMAKE_AR llvm-lib)
set(CMAKE_RC_COMPILER llvm-rc)
set(CMAKE_C_COMPILER_TARGET x86_64-pc-windows-msvc)
set(CMAKE_CXX_COMPILER_TARGET x86_64-pc-windows-msvc)
EOF

# clang-cl reads INCLUDE, lld-link reads LIB. Both are semicolon-separated
# Windows paths; CMake's compiler checks run with this environment too.
export INCLUDE="$splat/crt/include;$splat/sdk/include/ucrt;$splat/sdk/include/um;$splat/sdk/include/shared"
export LIB="$splat/crt/lib/x86_64;$splat/sdk/lib/um/x86_64;$splat/sdk/lib/ucrt/x86_64"

if [[ $clean -eq 1 ]]; then
    rm -rf "$build"
fi

# CMake's MSVC link driver asks for a manifest tool. Fedora's CMake finds
# llvm-mt on its own; Ubuntu's CMake invokes a `CMAKE_MT-NOTFOUND` unless told.
mt=()
if command -v llvm-mt >/dev/null; then
    mt=(-DCMAKE_MT=llvm-mt)
fi

cmake -S "$src" -B "$build" -G Ninja \
    -DCMAKE_TOOLCHAIN_FILE="$toolchain" \
    "${mt[@]}" \
    -DCMAKE_BUILD_TYPE=Release \
    -DBUILD_SHARED_LIBS=OFF \
    -DCMAKE_MSVC_RUNTIME_LIBRARY=MultiThreadedDLL \
    -DSHADERC_SKIP_TESTS=ON \
    -DSHADERC_SKIP_EXAMPLES=ON \
    -DSHADERC_SKIP_EXECUTABLES=ON \
    -DSHADERC_SKIP_COPYRIGHT_CHECK=ON \
    -DSHADERC_ENABLE_WERROR_COMPILE=OFF \
    -DSHADERC_ENABLE_SHARED_CRT=ON
cmake --build "$build" --target shaderc_combined

archive="$(find "$build" -name 'shaderc_combined.lib' -o -name 'libshaderc_combined.a' | head -1)"
if [[ -z "$archive" ]]; then
    echo "shaderc_combined was not produced under $build" >&2
    exit 1
fi

mkdir -p "$prefix/lib/pkgconfig" "$prefix/include/shaderc"
cp "$archive" "$prefix/lib/shaderc_combined.lib"
cp "$src/libshaderc/include/shaderc/"*.h "$prefix/include/shaderc/"
cp "$src/libshaderc/include/shaderc/"*.hpp "$prefix/include/shaderc/"

# Strip the leading `v`; pkg-config compares this against libplacebo's >=2019.1.
pc_version="${version#v}"
cat >"$prefix/lib/pkgconfig/shaderc.pc" <<EOF
prefix=$prefix
libdir=\${prefix}/lib
includedir=\${prefix}/include

Name: shaderc
Description: Shaderc static SPIR-V compiler (combined archive)
Version: $pc_version
Libs: -L\${libdir} -lshaderc_combined
Cflags: -I\${includedir}
EOF

echo
echo "built $prefix ($version)"
echo "link libplacebo against it:"
echo "  SHADERC_PREFIX=$prefix scripts/build-libplacebo-win.sh --clean"
