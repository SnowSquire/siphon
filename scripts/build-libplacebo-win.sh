#!/usr/bin/env bash
# Builds libplacebo for x86_64-pc-windows-msvc on Linux.
#
# clang-cl compiles it against the MSVC CRT and Windows SDK that `xwin` splatted
# into ~/.cache/xwin, llvm-lib archives and lld-link links, so no Windows machine
# is involved. The result is a `meson install` prefix the crate's
# `LIBPLACEBO_PREFIX` mode links against; `~/.cargo/config.toml` points at it for
# the Windows target.
#
# Usage: scripts/build-libplacebo-win.sh [--clean]
#
# Knobs (defaults match the dev box):
#   LIBPLACEBO_SRC    source checkout      ~/Projects/Code/Libs/libplacebo
#   LIBPLACEBO_PREFIX install prefix       $LIBPLACEBO_SRC/win-prefix
#   LIBPLACEBO_SPLAT  xwin CRT/SDK splat   ~/.cache/xwin
#   VULKAN_SDK        Vulkan headers       ~/Projects/Code/Libs/vulkan
#   LIBS_ROOT         parent for the above ~/Projects/Code/Libs
#   SHADERC_PREFIX    static shaderc       unset: no GLSL compiler
#
# Meson needs jinja2 in its own Python (libplacebo generates code with it); the
# uv-managed meson tool env does not ship it:
#   uv pip install --python ~/.local/share/uv/tools/meson/bin/python jinja2
#
# With SHADERC_PREFIX the shaderc archive from scripts/build-shaderc-win.sh is
# linked into the DLL and the meson summary reports `shaderc: YES`. Without it
# the build has no GLSL compiler: it links, but shaders cannot be compiled at
# run time, so that prefix is only good for the cross-check.

set -euo pipefail

root="${LIBS_ROOT:-$HOME/Projects/Code/Libs}"
src="${LIBPLACEBO_SRC:-$root/libplacebo}"
prefix="${LIBPLACEBO_PREFIX:-$src/win-prefix}"
splat="${LIBPLACEBO_SPLAT:-$HOME/.cache/xwin}"
vulkan="${VULKAN_SDK:-$root/vulkan}"
shaderc="${SHADERC_PREFIX:-}"
build="$src/build-win"
cross="$root/msvc-cross.ini"

clean=0
if [[ "${1:-}" == "--clean" ]]; then
    clean=1
fi

for tool in clang-cl llvm-lib llvm-rc lld-link meson ninja; do
    if ! command -v "$tool" >/dev/null; then
        echo "missing $tool; the Windows cross-check needs LLVM (clang-cl, lld) and meson" >&2
        exit 1
    fi
done
if [[ -n "$shaderc" ]] && ! command -v pkg-config >/dev/null; then
    echo "missing pkg-config; the shaderc dependency is found through it" >&2
    exit 1
fi

if ! "$(command -v meson)" --version >/dev/null; then
    echo "meson is present but cannot run" >&2
    exit 1
fi
meson_python="$(head -1 "$(command -v meson)" | sed 's/^#!//')"
if ! "$meson_python" -c 'import jinja2' >/dev/null 2>&1; then
    echo "meson's Python has no jinja2: uv pip install --python $meson_python jinja2" >&2
    exit 1
fi

if [[ ! -d "$splat/crt/include" ]]; then
    echo "no xwin splat at $splat: xwin --accept-license --cache-dir ~/.cache/xwin-cache splat --output ~/.cache/xwin" >&2
    exit 1
fi

if [[ ! -d "$src/.git" ]]; then
    echo "cloning libplacebo into $src"
    mkdir -p "$(dirname "$src")"
    cached="$HOME/.local/share/opencode/repos/github.com/haasn/libplacebo@master"
    if [[ -d "$cached/.git" ]]; then
        git clone --quiet "$cached" "$src"
    else
        git clone --quiet https://github.com/haasn/libplacebo "$src"
    fi
fi

# Khronos' Vulkan headers are platform-neutral; libplacebo's public headers
# include them and its generator wants the registry XML next to them.
if [[ ! -f "$vulkan/Include/vulkan/vulkan.h" ]]; then
    echo "installing Vulkan headers into $vulkan"
    mkdir -p "$vulkan/Include"
    cp -a /usr/include/vulkan "$vulkan/Include/"
    cp -a /usr/include/vk_video "$vulkan/Include/"
fi
registry="/usr/share/vulkan/registry/vk.xml"
if [[ ! -f "$registry" ]]; then
    # Some distributions split the registry out of the headers package.
    registry="$vulkan/vk.xml"
    if [[ ! -f "$registry" ]]; then
        echo "no Vulkan registry found; fetching it into $registry"
        curl -fsSL https://raw.githubusercontent.com/KhronosGroup/Vulkan-Headers/main/registry/vk.xml -o "$registry"
    fi
fi

includes=(
    "/imsvc$splat/crt/include"
    "/imsvc$splat/sdk/include/ucrt"
    "/imsvc$splat/sdk/include/um"
    "/imsvc$splat/sdk/include/shared"
    "/imsvc$vulkan/Include"
)
libs=(
    "/libpath:$splat/crt/lib/x86_64"
    "/libpath:$splat/sdk/lib/um/x86_64"
    "/libpath:$splat/sdk/lib/ucrt/x86_64"
)

array() {
    local out="[" item
    for item in "$@"; do
        out+="'$item', "
    done
    printf '%s]' "${out%, }"
}

cat >"$cross" <<EOF
# Generated by siphon's scripts/build-libplacebo-win.sh: a meson cross file that
# builds Windows x86_64/MSVC code with clang-cl and the xwin CRT/SDK.

[binaries]
c = 'clang-cl'
cpp = 'clang-cl'
ar = 'llvm-lib'
strip = 'llvm-strip'
windres = 'llvm-rc'
pkgconfig = 'pkg-config'

[host_machine]
system = 'windows'
subsystem = 'windows'
kernel = 'nt'
cpu_family = 'x86_64'
cpu = 'x86_64'
endian = 'little'

[built-in options]
c_args = $(array --target=x86_64-pc-windows-msvc -fuse-ld=lld "${includes[@]}")
cpp_args = $(array --target=x86_64-pc-windows-msvc -fuse-ld=lld "${includes[@]}")
c_link_args = $(array "${libs[@]}")
cpp_link_args = $(array "${libs[@]}")

[properties]
needs_exe_wrapper = true
EOF

# `find_library('shlwapi')` goes through clang-cl's own search, which reads
# INCLUDE and LIB rather than meson's arguments.
export INCLUDE="$splat/crt/include;$splat/sdk/include/ucrt;$splat/sdk/include/um;$splat/sdk/include/shared"
export LIB="$splat/crt/lib/x86_64;$splat/sdk/lib/um/x86_64;$splat/sdk/lib/ucrt/x86_64"

if [[ -n "$shaderc" ]]; then
    if [[ ! -f "$shaderc/lib/pkgconfig/shaderc.pc" ]]; then
        echo "SHADERC_PREFIX=$shaderc has no lib/pkgconfig/shaderc.pc; run scripts/build-shaderc-win.sh" >&2
        exit 1
    fi
    shaderc_option=enabled
else
    shaderc_option=disabled
    echo "note: SHADERC_PREFIX is unset, so this prefix has no GLSL compiler" >&2
fi

options=(
    --cross-file "$cross"
    --prefix "$prefix"
    --libdir lib
    --buildtype release
    -Dvulkan=enabled
    -Dvk-proc-addr=disabled
    "-Dvulkan-registry=$registry"
    -Db_vscrt=md
    -Dopengl=disabled
    -Dd3d11=disabled
    -Dglslang=disabled
    "-Dshaderc=$shaderc_option"
    -Ddovi=disabled
    -Dlibdovi=disabled
    -Dlcms=disabled
    -Dxxhash=disabled
    -Dunwind=disabled
    -Ddemos=false
    -Dtests=false
)

if [[ $clean -eq 1 ]]; then
    rm -rf "$build"
fi
# pkg-config has to see the target shaderc, not anything installed for the host.
if [[ -n "$shaderc" ]]; then
    export PKG_CONFIG_PATH="$shaderc/lib/pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"
fi
if [[ -d "$build/meson-private" ]]; then
    meson setup --reconfigure "$build" "$src" "${options[@]}"
else
    meson setup "$build" "$src" "${options[@]}"
fi
meson compile -C "$build"
meson install -C "$build"

echo
echo "built $prefix"
echo "run cargo through the wrapper, which exports the prefix for this target:"
echo "  scripts/cargo-win.sh clippy -p siphon-ui --all-targets"
